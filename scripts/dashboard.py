def _step_total(m):
    """'current / total' step label; '?' until total is known."""
    steps = m.get("steps") or []
    cur = steps[-1] if steps else 0
    total = m.get("total")
    return "%s / %s" % (cur, total if total else "?")


def _training_header(snap):
    """Stat cards + status + progress — rendered at the very top of the page."""
    t = snap["training"]
    tr = t.get("detail", {}) if isinstance(t.get("detail"), dict) else {}
    status = tr.get("status", "not started")
    tag = tr.get("tag", "-")
    dataset = tr.get("dataset", "-")
    out = tr.get("out", "-")
    loss = tr.get("train_loss")
    samples = tr.get("samples", "-")
    m = t.get("metrics", {})
    step_time = (str(m.get("step_time_s")) + "s") if m.get("step_time_s") is not None else "-"
    eta = _fmt_secs(m.get("eta_sec"))

    h = ["<h2>Training</h2>"]
    h.append('<div class="stats">'
             '<div class="stat"><div class="k">step</div>'
             '<div class="v" id="stat-step">%s</div></div>'
             '<div class="stat"><div class="k">last loss</div>'
             '<div class="v" id="stat-loss">%s</div></div>'
             '<div class="stat"><div class="k">step time</div>'
             '<div class="v" id="stat-time">%s</div></div>'
             '<div class="stat"><div class="k">time remaining</div>'
             '<div class="v" id="stat-eta">%s</div></div></div>'
             % (_step_total(m), _loss_now(m), step_time, eta))
    h.append('<div class="card">status <b>%s</b> &middot; tag %s &middot; '
             'dataset %s &middot; output %s</div>'
             % (html.escape(str(status)), html.escape(str(tag)),
                html.escape(str(dataset)), html.escape(str(out))))
    if status == "done" and loss is not None:
        try:
            h.append('<div class="card ok">final loss %.4f</div>' % float(loss))
        except (ValueError, TypeError):
            pass
    elif t.get("stale"):
        # The state file says a run is in progress; the process that wrote it is
        # gone, so say that instead of mirroring the claim.
        h.append('<div class="card warn">stopped &mdash; the trainer process for '
                 'this run is gone (log: %s)</div>'
                 % html.escape(str(t.get("log_file") or "-")))
    elif status == "running":
        h.append('<div class="card active">training &middot; log: %s</div>'
                 % html.escape(str(t.get("log_file", "-"))))
    if samples != "-":
        h.append('<div class="small">samples <b>%s</b></div>' % html.escape(str(samples)))
    steps = m.get("steps") or []
    total = m.get("total")
    if steps and total:
        try:
            pct = 100.0 * float(steps[-1]) / float(total)
            h.append('<div class="bar"><div style="width:%.1f%%"></div></div>'
                     '<div class="small">%.1f%% complete</div>' % (pct, pct))
        except (ValueError, ZeroDivisionError):
            pass
    return h


def _corpus_panel(snap):
    """'What the model is learning' — masking + corpus health, from measurements."""
    c = snap.get('corpus') or {}
    tr = c.get('train') or {}
    ve = c.get('verify') or {}
    fi = c.get('fit') or {}
    h = ['<h2>What the model is learning</h2>', '<div class="card">']
    h.append('<div id="corpus-findings">')
    for w in c.get('warnings') or []:
        h.append('<div class="warn">&#9888; %s</div>' % html.escape(str(w)))
    for n in c.get('notes') or []:
        h.append('<div class="small">&#8226; %s</div>' % html.escape(str(n)))
    if not (c.get('warnings') or c.get('notes')):
        h.append('<div class="small">no corpus has been measured yet</div>')
    h.append('</div>')

    if tr:
        h.append('<h3>Training run (labels actually trained on)</h3><table>')
        for key, label in (('file', 'state file'), ('tag', 'tag'),
                           ('dataset', 'corpus'), ('prompt_loss', 'loss on'),
                           ('rows', 'corpus rows'), ('rows_used', 'rows trained'),
                           ('dropped_no_answer', 'rows dropped, no answer'),
                           ('answer_token_share', 'answer share of tokens'),
                           ('max_len', 'max_len'), ('max_steps', 'max_steps'),
                           ('lr', 'lr'), ('loss', 'final loss'),
                           ('status', 'status')):
            v = tr.get(key)
            if v is None:
                continue
            if key == 'loss' and not tr.get('loss'):
                continue
            if key == 'prompt_loss':
                v = ('answers only (masked)' if v == 'masked'
                     else 'prompt + answer (diluted)')
            if key == 'answer_token_share' and isinstance(v, (int, float)):
                v = '%.1f%%' % (100 * v)
            h.append('<tr><td>%s</td><td><b>%s</b></td></tr>'
                     % (html.escape(label), html.escape(str(v))))
        h.append('</table>')
    else:
        h.append('<div class="small">(no training run recorded yet)</div>')

    if ve:
        cls = ve.get('classes') or {}
        h.append('<h3>Corpus health at max_len=%s <span class="small">(%s)</span></h3>'
                 % (html.escape(str(ve.get('max_len'))),
                    html.escape(str(ve.get('file')))))
        h.append('<div class="stats">')
        for label, val, cls_ in (
                ('rows', ve.get('rows'), ''),
                ('complete', cls.get('complete'), 'ok'),
                ('partial', cls.get('partial'), 'warn'),
                ('answer cut away', cls.get('answer_cut'), 'bad'),
                ('prompt-trimmed rows',
                 (fi.get('prompt_trimmed_rows')
                  if fi.get('prompt_trimmed_rows') is not None
                  else (ve.get('rewrites') or {}).get('prompt')), ''),
                ('answers kept', (('%s%%' % ve.get('answer_tokens_kept_pct'))
                                  if ve.get('answer_tokens_kept_pct') is not None
                                  else None), ''),
                ('terminator survives', (('%s%%' % ve.get('terminator_pct'))
                                         if ve.get('terminator_pct') is not None
                                         else None), 'ok'),
                ('duplicate groups', ve.get('duplicate_groups'), ''),
                ('anchor overlap', ve.get('anchor_overlap'),
                 'bad' if ve.get('anchor_overlap') else 'ok')):
            if val is None:
                continue
            h.append('<div class="stat"><div class="k">%s</div>'
                     '<div class="v %s">%s</div></div>'
                     % (html.escape(label), cls_, html.escape(str(val))))
        h.append('</div>')
        lt = ve.get('len_tokens') or {}
        h.append('<div class="small">corpus %s</div>'
                 % html.escape(str(ve.get('corpus'))))
        if lt:
            h.append('<div class="small">row tokens: median %s, p90 %s, max %s</div>'
                     % (lt.get('median'), lt.get('p90'), lt.get('max')))
    if fi:
        h.append('<h3>Fit to budget <span class="small">(%s)</span></h3>'
                 % html.escape(str(fi.get('file'))))
        h.append('<div class="small">%s rows &rarr; %s kept, %s trimmed; dropped: %s</div>'
                 % (fi.get('rows_in'), fi.get('rows_out'), fi.get('trimmed_rows'),
                    html.escape(json.dumps(fi.get('dropped') or {}))))
    h.append('</div>')
    return h


def _queue_panel(snap):
    """The dataset queue as its own section: order, next step, and controls.

    Reorder/skip is refused for whatever the pipeline is working on *right now*
    (the row says so rather than silently ignoring the click), and none of these
    controls touch the local files — deletion stays gated on a passed iteration.
    """
    d = snap.get('hfd') or {}
    items = d.get('items') or []
    q = d.get('queue') or {}
    h = ['<h2>Dataset queue</h2>', '<div class="card">']
    act = q.get('active')
    staled = q.get('stalled') or []
    bits = '%d pending' % q.get('pending', 0)
    if act:
        bits += ' &middot; <b>working on %s</b>' % html.escape(str(act))
    if staled:
        bits += (' &middot; <span class="pill warn">stalled</span> %s '
                 '(the runner that claimed these is gone &mdash; the queue '
                 'resumes them at train)'
                 % ', '.join(html.escape(str(s)) for s in staled))
    wedged = q.get('wedged') or []
    if wedged:
        bits += (' &middot; <span class="pill bad">wedged</span> %s '
                 '(alive but silent: no log growth and no CPU use &mdash; '
                 '<b>Fix stuck job</b> below)'
                 % ', '.join(html.escape(str(w)) for w in wedged))
    h.append('<div class="small">%s &middot; queue order is the order they are '
             'trained in &middot; skipping keeps files, deleting is gated on a '
             'passed iteration</div>' % bits)
    h.append('<div class="ctl" style="margin-top:8px">')
    h.append('<label>add to queue<input id="queue-add" size="40" '
             'placeholder="https://huggingface.co/datasets/org/name"></label>')
    h.append('<button class="act start" id="queue-add-btn">Add</button>')
    h.append('<button class="act" id="queue-plan-btn">Plan queue</button>')
    h.append('<button class="act stop" id="queue-stop-btn" '
             'title="stop the job the queue is running right now (files are kept; '
             'the queue resumes the row on its next pass)">Stop running job</button>')
    h.append('<button class="act" id="queue-unstick-btn" '
             'title="for a runner that is alive but doing nothing (no log growth '
             'and no CPU use): end its process tree and rewind the row to the stage '
             'its files reached, so the queue retries it (files are kept)">'
             'Fix stuck job</button>')
    h.append('</div><div id="queue-status"></div>'
             '<pre id="queue-plan" style="display:none"></pre>')
    h.append('</div>')

    if not items:
        h.append('<div class="card">queue is empty &mdash; add a dataset above or '
                 'use the panel further down to link one</div>')
        return h
    h.append('<table><tr><th>#</th><th>Dataset</th><th>State</th>'
             '<th>Next</th><th>Rows</th><th>On disk</th><th>Move / skip</th></tr>')
    for it in items:
        locked = it.get('locked')
        tone = ('ok' if it.get('state') in ('learned_verified', 'dropped')
                else 'bad' if it.get('state') in ('error', 'not_trainable')
                else 'run' if it.get('active') else 'warn')
        pills = ['<span class="pill %s">%s</span>'
                 % (tone, html.escape(str(it.get('state'))))]
        if it.get('stalled'):
            pills.append('<span class="pill warn">stalled</span>')
        if it.get('wedged'):
            pills.append('<span class="pill bad">wedged%s</span>'
                         % ((' %dm' % round(it.get('silent_min')))
                            if it.get('silent_min') is not None else ''))
        if it.get('active'):
            pills.append('<span class="pill run">active</span>')
        elif not it.get('pending'):
            pills.append('<span class="pill">done</span>')
        dis = ' disabled' if locked else ''
        tip = (' title="locked: the pipeline is working on this dataset"'
               if locked else '')
        h.append('<tr><td>%s</td><td class="small">%s</td><td>%s</td>'
                 '<td class="small">%s</td><td>%s</td><td>%s</td><td>' % (
                     it.get('pos'), html.escape(str(it.get('id'))),
                     ' '.join(pills), html.escape(str(it.get('next_step'))),
                     it.get('fitted_rows') or it.get('rows') or '-',
                     html.escape(str(it.get('bytes_human')))))
        h.append('<button class="hfrow" data-qact="up" data-repo="%s"%s%s>&#9650;</button>'
                 % (html.escape(str(it.get('id'))), dis, tip))
        h.append('<button class="hfrow" data-qact="down" data-repo="%s"%s%s>&#9660;</button>'
                 % (html.escape(str(it.get('id'))), dis, tip))
        skip_label = 'unskip' if it.get('state') == 'skipped' else 'skip'
        skip_act = 'unskip' if it.get('state') == 'skipped' else 'skip'
        h.append('<button class="hfrow" data-qact="%s" data-repo="%s"%s%s>%s</button>'
                 % (skip_act, html.escape(str(it.get('id'))), dis, tip, skip_label))
        if it.get('active'):
            # The row the pipeline is working on right now: the one place a stop
            # must be reachable. run_state decides the pid; files are kept.
            h.append('<button class="hfrow" data-act="stop" data-repo="%s">stop</button>'
                     % html.escape(str(it.get('id'))))
        h.append('</td></tr>')
    h.append('</table>')
    return h


