def _loss_now(m):
    losses = m.get("losses") or []
    return "%.4f" % losses[-1] if losses else "-"


def _fmt_secs(sec):
    if sec is None:
        return "-"
    sec = int(sec)
    hh, rem = divmod(sec, 3600)
    mm, ss = divmod(rem, 60)
    if hh:
        return "%dh %dm" % (hh, mm)
    if mm:
        return "%dm %ds" % (mm, ss)
    return "%ds" % ss


