#!/usr/bin/env python3
"""Turn a raw source-code corpus into supervised (prompt, completion) pairs.

`bigcode/starcoderdata` is 289.5 GB of permissively licensed source code in
per-language directories, with columns
`[id, content, max_stars_count, max_stars_repo_name, max_stars_repo_path]` —
no `messages`, no prompt/answer pair. The ingester therefore reports
`not_trainable`, which is correct: there is nothing there to *map*.

It is still the largest code signal on this box, so this script synthesises the
supervision instead of hunting for it. Each file becomes a "continue this file"
example: the head of the file is the prompt, the following lines are the
completion, with a language-appropriate instruction in front. That is the
FIM-style objective StarCoder itself was trained on, and it needs no teacher, no
GPU and no network — the pairing is a deterministic function of the file, so a
corpus built from the same slice is byte-identical every time (see plan.md on why
a fingerprintable corpus matters).

Everything it refuses is counted in the manifest's `drops`, the way the ingester
reports its own, so "how much did we lose, and why" has an answer.

    python scripts/code_sft.py --root cache/datasets/bigcode--starcoderdata ^
        --lang python,javascript,typescript --max-files 60 --limit 4000 ^
        --tag starcoderdata-code
"""
from __future__ import annotations

import argparse
import glob
import hashlib
import json
import os
import re
import sys
import time
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import aether_env  # noqa: E402 - caches/temp stay on the repo drive (never C:)
aether_env.pin_caches()

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATASETS = os.path.join(ROOT, "datasets")
LOGS = os.path.join(ROOT, "logs")
REPO = "bigcode/starcoderdata"
DEFAULT_SYSTEM = ("You are a precise coding assistant. No preamble, "
                  "no meta-commentary.")

# Directory name -> how it should read in an instruction. Anything missing falls
# back to a title-cased dir name, so a new language never breaks the run.
LANG_NAMES = {
    "python": "Python", "javascript": "JavaScript", "typescript": "TypeScript",
    "c": "C", "cpp": "C++", "c-sharp": "C#", "java": "Java", "go": "Go",
    "rust": "Rust", "ruby": "Ruby", "php": "PHP", "shell": "shell", "sql": "SQL",
    "kotlin": "Kotlin", "swift": "Swift", "scala": "Scala", "lua": "Lua",
    "r": "R", "perl": "Perl", "haskell": "Haskell", "elixir": "Elixir",
    "dart": "Dart", "html": "HTML", "css": "CSS", "yaml": "YAML",
    "dockerfile": "Dockerfile", "makefile": "Makefile", "cuda": "CUDA",
    "batchfile": "batch", "powershell": "PowerShell", "solidity": "Solidity",
    "vhdl": "VHDL", "verilog": "Verilog", "fortran": "Fortran", "julia": "Julia",
    "matlab": "MATLAB", "objective-c": "Objective-C", "assembly": "assembly",
    "markdown": "Markdown", "tex": "LaTeX", "json": "JSON", "xml": "XML",
}

# starcoderdata prefixes each file with metadata markers, some inline: `<reponame>`,
# `<gh_stars>1-10`, `<filename>`, `<issue>`. They are corpus bookkeeping, not code, so
# the model should never see them.
MARKER_LINES = re.compile(
    r"^<(reponame|gh_stars|filename|issue|pr|commit|commit_message|jupyter)>.*$",
    re.MULTILINE)
GENERATED = re.compile(
    r"(do not edit|@generated|auto-?generated|this file was generated|"
    r"generated by|autogenerated)", re.IGNORECASE)
ALNUM = re.compile(r"[A-Za-z0-9]")


def now():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def lang_name(lang):
    """The label to use in an instruction ('python' -> 'Python')."""
    return LANG_NAMES.get((lang or "").lower(),
                          (lang or "code").replace("-", " ").title())


def instruction(lang):
    return ("Continue this %s file from where it stops. Output only the code "
            "that follows — no commentary, no fences." % lang_name(lang))


def strip_metadata(text):
    """Drop starcoderdata's metadata marker lines (`<reponame>`, `<gh_stars>`, ...)."""
    return MARKER_LINES.sub("", text or "")


def split_file(text, min_chars=400, min_lines=8, max_chars=12000,
               min_head=200, min_completion=80, head_ratio=0.6):
    """(head, tail, note) for one file — or (None, None, drop_reason).

    `note` is "windowed" when the file was cut to `max_chars`: a 200 KB file still
    yields one usable example instead of being thrown away, and the manifest records
    that it was cut.
    """
    text = strip_metadata(text).replace("\r\n", "\n").replace("\r", "\n")
    if len(text) < min_chars:
        return None, None, "too_short"
    window, windowed = text[:max_chars], len(text) > max_chars
    lines = window.split("\n")
    if len(lines) < min_lines:
        return None, None, "too_few_lines"
    if GENERATED.search(text[:600]):
        return None, None, "generated_marker"
    if len(ALNUM.findall(window)) / max(len(window), 1) < 0.35:
        return None, None, "low_signal"
    if max(len(l) for l in lines) > 300:
        return None, None, "minified"

    starts, off = [], 0
    for l in lines:
        starts.append(off)
        off += len(l) + 1

    def indent(s):
        return len(s) - len(s.lstrip(" \t"))

    target = max(min_head, int(len(window) * head_ratio))
    pick = None
    for i in range(1, len(starts)):
        # Prefer a dedent: a completion that opens a fresh block is answerable,
        # one that resumes mid-expression is a guessing game.
        if starts[i] >= target and lines[i].strip() \
                and indent(lines[i]) <= indent(lines[i - 1]):
            pick = i
            break
    if pick is None:
        pick = next((i for i in range(1, len(starts)) if starts[i] >= target),
                    len(starts) - 1)
    cut = starts[pick]
    head, tail = window[:cut].rstrip(), window[cut:].strip("\n")
    if len(head) < min_head:
        return None, None, "head_too_small"
    if len(tail) < min_completion:
        return None, None, "completion_too_small"
    return head, tail, ("windowed" if windowed else "ok")


def build_pair(text, lang, repo, path, stars, idx, num, caps):
    """One record in the ingester's schema, so verify/fit/train need no changes."""
    head, tail, note = split_file(text, **caps)
    if head is None:
        return None, note
    rec = {
        "id": "sc-%06d" % num,
        "source": "starcoderdata",
        "recipe": "code_continue",
        "system": DEFAULT_SYSTEM,
        "prompt": "%s\n\n%s" % (instruction(lang), head),
        "completion": tail,
        "provenance": {"repo": repo, "path": path, "lang": lang,
                       "stars": stars, "row_index": idx},
        "meta": {"prompt_chars": len(head) + len(instruction(lang)) + 2,
                 "completion_chars": len(tail), "windowed": note == "windowed"},
    }
    return rec, note


def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def shards(root, langs):
    """[(lang, parquet path)] in the order asked for, so runs are comparable."""
    out = []
    for lang in langs:
        out += [(lang, p) for p in
                sorted(glob.glob(os.path.join(root, lang.strip(), "*.parquet")))]
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description="raw code -> SFT prompt/completion pairs")
    ap.add_argument("--root", default=os.path.join(ROOT, "cache", "datasets",
                                                   "bigcode--starcoderdata"))
    ap.add_argument("--lang", default="python,javascript,typescript",
                    help="comma-separated language directories to read")
    ap.add_argument("--tag", default="starcoderdata-code")
    ap.add_argument("--limit", type=int, default=2000,
                    help="pairs to write (0 = no cap)")
    ap.add_argument("--max-files", type=int, default=2000,
                    help="files to inspect (0 = no cap). One pair per file, so this "
                         "is also the ceiling on examples")
    ap.add_argument("--min-chars", type=int, default=400)
    ap.add_argument("--min-lines", type=int, default=8)
    ap.add_argument("--max-chars", type=int, default=5200,
                    help="file window; prompt+completion must stay inside it. 5200 "
                         "chars is ~1,300 tokens of code, so verify_dataset at "
                         "max_len=1536 does not cut the answer away (12,000 chars "
                         "did: 312 of 2,393 rows lost their answer entirely)")
    ap.add_argument("--min-head", type=int, default=200)
    ap.add_argument("--min-completion", type=int, default=80)
    ap.add_argument("--head-ratio", type=float, default=0.6)
    ap.add_argument("--batch", type=int, default=256)
    ap.add_argument("--per-lang", type=int, default=700,
                    help="files to read per language (0 = no cap) — without it the "
                         "first language fills the whole quota from one shard")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    import pyarrow.parquet as pq

    langs = [l for l in (a.lang or "").split(",") if l.strip()]
    caps = {"min_chars": a.min_chars, "min_lines": a.min_lines,
            "max_chars": a.max_chars, "min_head": a.min_head,
            "min_completion": a.min_completion, "head_ratio": a.head_ratio}
    os.makedirs(DATASETS, exist_ok=True)
    out_path = os.path.join(DATASETS, a.tag + ".jsonl")
    drops, notes, seen = {}, {}, set()
    rows, inspected, read_shards = 0, 0, []
    t0 = time.time()
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        for lang, shard in shards(a.root, langs):
            if a.max_files and inspected >= a.max_files:
                break
            lang_seen = 0
            read_shards.append(os.path.relpath(shard, a.root))
            pf = pq.ParquetFile(shard)
            idx = 0
            for batch in pf.iter_batches(
                    batch_size=a.batch,
                    columns=["content", "max_stars_repo_name",
                             "max_stars_repo_path", "max_stars_count"]):
                if a.per_lang and lang_seen >= a.per_lang:
                    break
                d = batch.to_pydict()
                for i in range(len(d["content"])):
                    if a.max_files and inspected >= a.max_files:
                        break
                    if a.per_lang and lang_seen >= a.per_lang:
                        break
                    inspected += 1
                    lang_seen += 1
                    content = d["content"][i] or ""
                    key = hashlib.sha1(content.encode("utf-8", "ignore")).hexdigest()
                    own = key not in seen
                    seen.add(key)
                    if not own:
                        drops["duplicate"] = drops.get("duplicate", 0) + 1
                        idx += 1
                        continue
                    rec, note = build_pair(
                        content, lang, d["max_stars_repo_name"][i],
                        d["max_stars_repo_path"][i], d["max_stars_count"][i],
                        idx, rows, caps)
                    idx += 1
                    if rec is None:
                        drops[note] = drops.get(note, 0) + 1
                        continue
                    notes[note] = notes.get(note, 0) + 1
                    fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
                    rows += 1
                    if a.limit and rows >= a.limit:
                        break
                if a.limit and rows >= a.limit:
                    break
            if a.limit and rows >= a.limit:
                break

    manifest = {
        "tag": a.tag, "created_utc": now(), "purpose": "training",
        "params": dict(caps, lang=langs, limit=a.limit, max_files=a.max_files),
        "source": {"repo": REPO, "root": os.path.relpath(a.root, ROOT),
                   "shards": read_shards},
        "counts": {"inspected": inspected, "written": rows, "drops": drops,
                   "notes": notes},
        "output": {"jsonl": os.path.relpath(out_path, ROOT), "rows": rows,
                   "sha256": sha256_file(out_path)},
        "recipe": ("code_continue: the head of each file is the prompt, the lines "
                   "that follow are the completion. Deterministic — no teacher, no "
                   "sampling — so the same slice always yields the same bytes."),
        "provenance": {"tool": "scripts/code_sft.py",
                       "seconds": round(time.time() - t0, 1)},
    }
    with open(os.path.join(DATASETS, a.tag + ".manifest.json"), "w",
              encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2, ensure_ascii=False)
    print("[code-sft] %d pairs from %d files -> %s"
          % (rows, inspected, os.path.relpath(out_path, ROOT)))
    print("[code-sft] drops: %s" % (drops or "none"))
    print("[code-sft] notes: %s" % (notes or "none"))
    return 0 if rows else 1


CAPS = {"min_chars": 400, "min_lines": 8, "max_chars": 5200, "min_head": 200,
        "min_completion": 80, "head_ratio": 0.6}


def selftest():
    """Offline checks of the pairing rules (no parquet, no network, no writes)."""
    ok = True

    def check(good, label, extra=""):
        nonlocal ok
        ok = ok and bool(good)
        print("[selftest] %s %s%s" % ("ok  " if good else "FAIL", label,
                                      (" — %s" % extra) if extra else ""))

    src = ("<reponame>org/proj\nimport os\n\n\n"
           + "".join("def f%d(x):\n    y = x + %d\n    return y * 2\n\n\n" % (i, i)
                     for i in range(12))
           + "class Thing:\n    def run(self):\n        return f3(2)\n")
    norm = strip_metadata(src).replace("\r\n", "\n")
    head, tail, note = split_file(src)
    check(head and tail and note == "ok", "a normal file yields a pair", note)
    check(bool(head) and "<reponame>" not in head,
          "the reponame marker line is stripped")
    check(norm.startswith(head), "the head is the file's own text, verbatim")
    check(norm.index(tail.strip()[:40]) > len(head),
          "the completion is the text that follows the prompt")
    check(len(norm) > len(head) and norm[len(head)] == "\n",
          "the split lands on a line boundary")
    check(split_file("x = 1\n")[2] == "too_short", "a tiny file is dropped")
    check(split_file("// do not edit this file\n" + src)[2] == "generated_marker",
          "a generated-file banner is dropped")
    check(split_file(("x" * 400 + "\n") * 12)[2] == "minified",
          "minified data is dropped")
    check(split_file("------\n" * 70)[2] == "low_signal",
          "a file with almost no alphanumerics is dropped")
    rec, _ = build_pair(src, "python", "org/proj", "p.py", 3, 0, 0, CAPS)
    check(rec is not None and set(rec) >= {"id", "source", "recipe", "system",
                                           "prompt", "completion", "provenance",
                                           "meta"},
          "the record matches the ingester's schema")
    check(rec["provenance"]["repo"] == "org/proj"
          and rec["recipe"] == "code_continue"
          and "ingested_utc" not in json.dumps(rec),
          "provenance is kept and no per-row wall-clock is stamped")
    again, _ = build_pair(src, "python", "org/proj", "p.py", 3, 0, 0, CAPS)
    check(json.dumps(rec, sort_keys=True) == json.dumps(again, sort_keys=True),
          "the same file yields byte-identical output")
    check(instruction("python").startswith("Continue this Python file")
          and instruction("c-sharp").startswith("Continue this C# file"),
          "language names read correctly in the instruction")
    print("[selftest] %s" % ("ALL OK" if ok else "FAILURES"))
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())


